#ifndef __APP_DATA_H
#define __APP_DATA_H

#include "main.h"

/* ------------------------------------------------------------------
 * 传感器数据结构 —— SensorTask → AlarmTask 通过队列传递
 * ------------------------------------------------------------------
 * 说明：
 *   用"值传递"而不是"指针传递" —— FreeRTOS 队列会把整个结构体
 *   拷贝进队列，接收方拿到的是独立副本，天然没有共享内存问题。
 * ------------------------------------------------------------------ */
typedef struct {
    float    temp;       /* 温度，单位 ℃        */
    float    humi;       /* 湿度，单位 %RH      */
    uint8_t  pir;        /* 0 = 无人, 1 = 有人  */
    uint16_t gas_raw;    /* 气体 ADC 原始值     */
    float    gas_v;      /* 气体电压，单位 V    */
    uint32_t tick;       /* 采集时刻（ms）      */
} sensor_data_t;


/* ------------------------------------------------------------------
 * 手动控制请求 —— CommTask（云端指令）→ AlarmTask（执行器）
 * ------------------------------------------------------------------
 * 为什么需要这个结构，而不是让 CommTask 直接写 GPIO？
 *
 *   ★ 因为执行器（LED/蜂鸣器）已经被 AlarmTask【独占】。
 *     如果 CommTask 也去写，就又回到"两个任务抢同一个 GPIO"的
 *     资源竞争问题 —— 谁最后写谁赢，状态不确定。
 *
 *   所以约定：**只有 AlarmTask 写执行器**。
 *   CommTask 只负责把"用户想要什么"写进这个结构，
 *   由 AlarmTask 在输出阶段把【自动报警】和【手动请求】合并。
 *
 * 为什么用"剩余周期数"而不是"目标时间戳"？
 *
 *   如果用 HAL_GetTick() + 3000 表示"响到什么时候"，
 *   会有 32 位计时的回绕问题（49.7 天回绕一次），
 *   `now < until` 在回绕点会判断错误。
 *   用"还剩多少个 50ms 周期"就完全避开这个问题 ——
 *   它只是一个递减的计数器，和绝对时间无关。
 * ------------------------------------------------------------------ */
typedef struct {
    volatile uint16_t beep_remain;   /* 蜂鸣器还需响多少个 50ms 周期（0=不响）*/
    volatile uint16_t led_remain;    /* 红灯还需亮多少个 50ms 周期（0=灭）  */
    volatile uint8_t  remote_locked; /* 1 = 手动测试中，阻止自动逻辑覆盖 */
} ctrl_request_t;

extern ctrl_request_t g_ctrl_req;

#endif /* __APP_DATA_H */